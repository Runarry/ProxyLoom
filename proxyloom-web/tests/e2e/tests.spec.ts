import { test, expect, type Page } from '@playwright/test'

const seed = JSON.parse(process.env.PROXYLOOM_M3_SEED ?? '{}') as { node: string; exit: string; chain: string; target: string; download_target: string; target_url: string }
async function login(page: Page) {
  await page.goto('/login')
  await page.locator('[name="username"]').fill(process.env.PROXYLOOM_E2E_USERNAME!)
  await page.locator('[name="password"]').fill(process.env.PROXYLOOM_E2E_PASSWORD!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '节点库', exact: true })).toBeVisible()
}
async function headers(page: Page, revision?: string) {
  const me = await page.request.get('/api/v1/auth/me'); expect(me.status()).toBe(200)
  return { Origin: new URL(process.env.PROXYLOOM_E2E_BASE_URL!).origin, 'X-CSRF-Token': (await me.json()).data.csrf_token, 'Content-Type': 'application/json', ...(revision ? { 'If-Match': `"r${revision}"` } : {}) }
}
async function read(page: Page, path: string) { const response = await page.request.get(`/api/v1${path}`); expect(response.status()).toBe(200); return (await response.json()).data }
