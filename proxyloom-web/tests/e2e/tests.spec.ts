test('download SSE reconnect restores snapshots and cancellation settles without repeating the download', async ({ page }) => {
  await page.goto(`/tests?subject=${seed.chain}`)
  await page.getByRole('button', { name: '选择测试参数', exact: true }).click()
  await page.getByRole('combobox', { name: '测试类型', exact: true }).selectOption('download_throughput')
  await page.getByLabel('登记目标', { exact: false }).selectOption(seed.download_target)
  await page.getByRole('button', { name: '创建测试任务', exact: true }).click()
  await expect(page).toHaveURL(/\/jobs\/[0-9a-f-]{36}$/)
  const id = new URL(page.url()).pathname.split('/').at(-1)!
  let streams = 0
  page.on('request', request => { if (request.url().endsWith('/events')) streams++ })
  await expect(page.getByText('限额下载 · 0 / 1', { exact: true })).toBeVisible({ timeout: 30000 })
  const beforeReconnect = streams
  await page.context().setOffline(true)
  await page.waitForTimeout(500)
  await page.context().setOffline(false)
  await expect(page.getByText('实时连接已建立', { exact: true })).toBeVisible({ timeout: 15000 })
  await expect.poll(() => streams, { timeout: 5000 }).toBeGreaterThan(beforeReconnect)
  const start = Date.now()
  await page.getByRole('button', { name: '取消整个批次', exact: true }).click()
  await expect(page.getByRole('heading', { name: '已取消', exact: true })).toBeVisible({ timeout: 5500 })
  expect(Date.now() - start).toBeLessThan(5500)
  await page.reload()
  await expect(page.getByRole('heading', { name: '已取消', exact: true })).toBeVisible()
  const batch = await read(page, `/jobs/${id}`)
  expect(batch.children[0].attempt).toBe(1)
  const results = await read(page, `/test-results?subject_id=${seed.chain}&type=download_throughput`)
  expect(results).toHaveLength(1)
  expect(results[0].state).toBe('canceled')
  expect(results[0].metrics.throughput_mbps).toBeUndefined()
})

test('register an HTTP target through the Chinese keyboard-accessible form and reject protected addresses', async ({ page }) => {
  await page.goto('/test-targets')
  await page.getByLabel('名称', { exact: true }).fill('浏览器受控目标')
  await page.getByLabel('HTTP(S) URL', { exact: true }).fill(`${seed.target_url}/check`)
  await page.getByRole('button', { name: '保存目标', exact: true }).click()
  await expect(page.getByText('测试目标已保存。实际测试仍会校验证书、状态与响应特征。', { exact: true })).toBeVisible()
  await expect(page.getByRole('row', { name: /浏览器受控目标/ })).toBeVisible()
  const response = await page.request.post('/api/v1/test-targets', { headers: { ...await headers(page), 'Idempotency-Key': crypto.randomUUID() }, data: { name: 'forbidden loopback', target: { url: 'http://127.0.0.1:22', allowed_types: ['connectivity'], expected_response: { status_codes: [200], max_response_bytes: 64, egress_ip_response: false }, limits: { duration_ms: 1000, max_bytes: 64 }, permission_basis: 'self_owned', redirect_policy: 'deny', verify_certificate: true, compression: 'disabled' } } })
  expect(response.status()).toBe(422)
})
